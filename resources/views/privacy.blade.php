    <h1>Privacy policy</h1>
    <p class="muted">CA Dashboard (app.kuhu.org.in) and the CA Dashboard Android app · Last updated 21 November 2026</p>

    <p>CA Dashboard is practice-management software used by chartered accountancy firms and their staff. It is published by RL Associates (Rajat Lakhani &amp; Associates, Chartered Accountants). This policy explains what the website and the Android app collect and why.</p>

    <h2>Who can use it</h2>
    <p>Only people who have been given an account by their firm can sign in. There is no public sign-up for individuals, and the app is not meant for children.</p>

    <h2>What we collect</h2>
    <ul>
        <li><strong>Account details</strong> – your name, email, mobile number, role and password (stored only as a secure hash).</li>
        <li><strong>Firm work data</strong> – clients, tasks, filings, invoices, payments, documents and other records that you and your colleagues enter. This belongs to your firm.</li>
        <li><strong>Phone notification token</strong> – if you allow notifications in the Android app, a token from Google Firebase Cloud Messaging so we can send you alerts. It is deleted when you sign out on that phone.</li>
        <li><strong>Usage logs</strong> – an activity log of changes made inside your firm's workspace, and standard server logs, used for security and troubleshooting.</li>
    </ul>

    <h2>Phone permissions</h2>
    <ul>
        <li><strong>Camera</strong> – only when you tap “Scan with camera” to photograph a document. The photo is uploaded to the client or record you chose.</li>
        <li><strong>Notifications</strong> – to show task, due-date and payment alerts. You can switch each type off in Settings → Notifications.</li>
        <li><strong>Fingerprint / face unlock</strong> – checked entirely by your phone. We never receive or store fingerprint or face data.</li>
    </ul>

    <h2>How the data is used</h2>
    <p>Only to run the service for your firm: showing your work, sending the reminders your firm has switched on (in-app, email, WhatsApp or phone notifications), producing invoices and reports, and keeping the system secure. We do not sell data, show ads or use the data for marketing.</p>

    <h2>Who it is shared with</h2>
    <p>Data is visible only to people in your own firm, according to their role. It is stored on our hosting provider's servers. Messages are delivered through the services your firm enables (email, WhatsApp Business, Google Firebase for phone notifications). We share data with authorities only when the law requires it.</p>

    <h2>Keeping and deleting data</h2>
    <p>Firm data is kept while the firm uses CA Dashboard, plus backups. Your firm's administrator can delete records, and can ask us to delete the whole workspace. To have your own account removed, ask your firm's administrator or contact us below.</p>

    <h2>Security</h2>
    <p>All traffic uses HTTPS. Passwords are hashed, saved client portal credentials are encrypted, sessions sign out after inactivity, and the Android app can be locked with your fingerprint or face.</p>

